def get_translation(key, lang="en", **kwargs):
    """Return the translated string for *key* in *lang*, optionally formatted."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    text = table.get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
